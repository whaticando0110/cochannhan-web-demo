const { mkdirSync, readFileSync, writeFileSync } = require('node:fs');
const { join, resolve } = require('node:path');

const [codec, input, output] = process.argv.slice(2);
if (!output) throw new Error('Usage: node pack-rampart-tiles.cjs <pixel-png.cjs> <tileset folder> <runtime folder>');
const { decode, encode } = require(resolve(codec));
const { tileSize, atlas, families, frames } = JSON.parse(readFileSync(join(input, 'tileset.json'), 'utf8'));
const source = decode(join(input, atlas.file));
if (source.width !== atlas.width || source.height !== atlas.height) throw new Error('Source atlas dimensions do not match the manifest');

const groups = {
  ground: { columns: 4, rows: 4, placements: {} },
  forest: { columns: 4, rows: 2, placements: {} },
  rampart: { columns: 6, rows: 4, placements: {
    'palisade-north': [0, 0], 'palisade-west': [1, 0], 'palisade-corner-nw': [2, 0],
    'platform-edge-south': [3, 0], 'platform-edge-east': [4, 0],
    'stairs-up-north': [0, 1], 'stairs-up-west': [2, 1],
  } },
};
Object.entries(families).filter(([family]) => family !== 'bamboo').forEach(([, ids], row) =>
  ids.forEach((id, col) => { groups.ground.placements[id] = [col, row]; })
);
families.bamboo.forEach((id, col) => { groups.forest.placements[id] = [col, 0]; });
['bamboo-fringe', 'bamboo-edge-south', 'bamboo-edge-east'].forEach((id, col) => {
  groups.forest.placements[id] = [col, 1];
});

const sheets = {};
const packed = {};
mkdirSync(output, { recursive: true });
for (const [name, group] of Object.entries(groups)) {
  const width = group.columns * tileSize;
  const height = group.rows * tileSize;
  const data = Buffer.alloc(width * height * 4);
  const covered = new Set();
  for (const [id, [col, row]] of Object.entries(group.placements)) {
    const frame = frames[id];
    if (!frame || packed[id]) throw new Error(`Missing or duplicate frame ${id}`);
    const x = col * tileSize;
    const y = row * tileSize;
    if (x + frame.width > width || y + frame.height > height ||
        frame.x + frame.width > source.width || frame.y + frame.height > source.height) {
      throw new Error(`Frame does not fit: ${id}`);
    }
    for (let r = row; r < row + frame.height / tileSize; r++) {
      for (let c = col; c < col + frame.width / tileSize; c++) {
        const key = r * group.columns + c;
        if (covered.has(key)) throw new Error(`Overlapping frame: ${id}`);
        covered.add(key);
      }
    }
    for (let dy = 0; dy < frame.height; dy++) {
      const start = ((frame.y + dy) * source.width + frame.x) * 4;
      source.data.copy(data, ((y + dy) * width + x) * 4, start, start + frame.width * 4);
    }
    packed[id] = { ...frame, sheet: name, x, y };
  }
  const file = `${name}.png`;
  sheets[name] = { file, width, height };
  writeFileSync(join(output, file), encode(data, width, height));
}
if (Object.keys(packed).length !== Object.keys(frames).length) throw new Error('The packed sheets omit an atlas frame');
const manifest = { tileSize, sheets, families, frames: packed };
writeFileSync(join(output, 'atlas.mjs'), `// Generated by scripts/pack-rampart-tiles.cjs.\nexport default ${JSON.stringify(manifest, null, 2)};\n`);
console.log(`Packed ${Object.keys(packed).length} frames into ${Object.keys(sheets).length} runtime sheets`);
